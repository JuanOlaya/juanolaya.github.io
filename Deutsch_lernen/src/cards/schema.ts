import { z } from 'zod';

/**
 * Shapes of the verb data under `Deutsch_lernen/verben/A1_A2_B1/json/`, inferred from the files as they are.
 * Objects are strict so a misspelt key (e.g. `perfect` for `perfekt`) is reported instead of ignored.
 */

/** CEFR sub-level used by groups and cards, e.g. `A1.1`, `B2.1`. */
export const SubLevelSchema = z
  .string()
  .regex(/^(A1|A2|B1|B2)\.[12]$/, 'expected a CEFR sub-level such as "A1.1"');

/** UTF-8 read as Windows-1252 leaves `Ã`/`Â` sequences behind; the U+FFFD marks bytes that were lost entirely. */
const MOJIBAKE_MARKERS = ['Ã', 'Â', String.fromCharCode(0xfffd)];
const CleanTextSchema = z
  .string()
  .refine(
    (text) => !MOJIBAKE_MARKERS.some((marker) => text.includes(marker)),
    'contains mojibake (broken UTF-8)',
  );

/** Pronoun → conjugated form, e.g. `{ ich: "baue auf", du: "baust auf", … }`. */
export const ConjugationTableSchema = z.record(z.string(), z.string());

export const ExampleSchema = z.strictObject({
  de: z.string(),
  es: z.string().optional(),
  en: z.string().optional(),
});

/** Pronoun → example sentence for that form. */
export const ExampleMapSchema = z.record(z.string(), ExampleSchema);

const WordEntrySchema = z.strictObject({
  word: z.string(),
  type: z.string().optional(),
  level: z.string().optional(),
  es: z.string().optional(),
  en: z.string().optional(),
  example: z.string().optional(),
});

const PhraseSchema = z.strictObject({
  expression: z.string(),
  translation: z.string(),
  example: z.string().optional(),
  example_es: z.string().optional(),
});

const StringListSchema = z.array(z.string());

/** One verb card: `json/cards/<verb>.json`. */
export const CardSchema = z.strictObject({
  verb: CleanTextSchema.min(1),
  es: z.string(),
  level: SubLevelSchema,
  group: z.int().positive().optional(),
  theme: z.string().optional(),
  themeGerman: z.string().optional(),
  themeEnglish: z.string().optional(),
  emoji: z.string().optional(),
  Wortart_type: z.literal('verb').optional(),
  card_es: z.string().optional(),
  en: z.string().optional(),
  en_verb: z.string().optional(),
  praesens: z.union([z.string(), ConjugationTableSchema]).optional(),
  perfekt: z.string().optional(),
  praeteritum: z.string().optional(),
  es_perfekt: z.string().optional(),
  en_perfekt: z.string().optional(),
  es_praeteritum: z.string().optional(),
  en_praeteritum: z.string().optional(),
  es_searchable: StringListSchema.optional(),
  es_perfekt_searchable: StringListSchema.optional(),
  es_praeteritum_searchable: StringListSchema.optional(),
  irregularPraesens: z.boolean().optional(),
  irregularPraeteritum: z.boolean().optional(),
  isSeparable: z.boolean().optional(),
  hasWortfamilie: z.boolean().optional(),
  vokalwechsel: z.string().optional(),
  tags: StringListSchema.optional(),
  case_tags: StringListSchema.optional(),
  note: z.string().optional(),
  note_es: z.string().optional(),
  note_perfekt: z.string().optional(),
  usage_note: z.string().optional(),
  example: z.string().optional(),
  example_es: z.string().optional(),
  wortfamilie: z.array(z.union([z.string(), WordEntrySchema])).optional(),
  wortfeld: z.array(z.union([z.string(), WordEntrySchema])).optional(),
  saetze: z.record(z.string(), z.array(PhraseSchema)).optional(),
});

/** One thematic group: `json/groups/<level>/<level>_group_<n>.json`. Source of truth for `verbs_index.json`. */
export const GroupSchema = z.strictObject({
  level: SubLevelSchema,
  theme: z.string(),
  germanName: z.string(),
  englishName: z.string(),
  spanishName: z.string(),
  germanDescription: z.string().optional(),
  spanishDescription: z.string().optional(),
  groupNameEnglish: z.string().optional(),
  verbs: z.array(z.string().min(1)).min(1),
});

/** `json/verbs_index.json`, generated by `tools/memodeutsch/verben/A1_A2_B1/update_index.js`. */
export const VerbsIndexSchema = z.strictObject({
  _DEVELOPER_WARNING: z.string(),
  lastUpdated: z.string().min(1),
  totalGroups: z.int().nonnegative(),
  totalVerbs: z.int().nonnegative(),
  groups: z.array(
    z.strictObject({
      level: SubLevelSchema,
      verbCount: z.int().nonnegative(),
      verbs: z.array(z.string()),
      groupNameGerman: z.string(),
      groupNameSpanish: z.string(),
      groupNumberPerLevel: z.int().positive(),
    }),
  ),
});

const PronounRowsSchema = z.array(
  z.strictObject({
    pronoun: z.string(),
    verbForm: z.string(),
    es: z.string().optional(),
    en: z.string().optional(),
  }),
);

/** One top-level value of a tense or example file: a note, a conjugation table, an example map or pronoun rows. */
const TenseValueSchema = z.union([z.string(), ConjugationTableSchema, ExampleMapSchema, PronounRowsSchema]);

/**
 * A per-verb tense file (`praesens/`, `praeteritum_konjugation/`, `perfekt_konjugation/`, `konjunktiv_ii/`).
 * Their layouts vary between generations of the data, so each top-level value only has to be one of the
 * shapes the app reads.
 */
export const TenseFileSchema = z.record(z.string(), TenseValueSchema);

/**
 * A per-verb example file (`examples/<tense>_examples/`). The app merges it into the verb and reads these keys as
 * pronoun → `{ de, es, en }`, so they must be example maps; older files may also carry conjugation tables or notes.
 */
export const ExampleFileSchema = z
  .object({
    praesens_examples: ExampleMapSchema.optional(),
    praesens_dativ: ExampleMapSchema.optional(),
    praesens_fragen: ExampleMapSchema.optional(),
    praesens_question_examples: ExampleMapSchema.optional(),
    perfekt_examples: ExampleMapSchema.optional(),
    praeteritum_examples: ExampleMapSchema.optional(),
    konjunktiv_ii_examples: ExampleMapSchema.optional(),
  })
  .catchall(TenseValueSchema);

/** One related word in `json/wortfamilie/<verb>.json`; only the keys the verb modal reads. */
const WortfamilieEntrySchema = z.strictObject({
  word: z.string().min(1),
  type: z.string().min(1),
  level: z.string().optional(),
  es: z.string().optional(),
  en: z.string().optional(),
  example: z.string().optional(),
  truco: z.string().optional(),
});

export const WortfamilieFileSchema = z.strictObject({
  wortfamilie: z.array(WortfamilieEntrySchema),
});

/**
 * Metadata of one group: `json/themes/<level>_<n>_theme.json`, e.g. `A2_1_10_theme.json`.
 * Written by the tools in `tools/memodeutsch/`; the app takes the same fields from the group files.
 */
export const ThemeSchema = z.strictObject({
  level: SubLevelSchema,
  group: z.int().positive(),
  theme: z.string().optional(),
  germanName: z.string().min(1),
  shortName: z.string().min(1),
  spanishName: z.string().min(1),
  englishName: z.string().optional(),
  description: z.string().optional(),
  germanDescription: z.string(),
  spanishDescription: z.string(),
  b1Rating: z.string(),
  examContext: z.string(),
  examContextEs: z.string(),
});

export type Card = z.infer<typeof CardSchema>;
export type Group = z.infer<typeof GroupSchema>;
export type VerbsIndex = z.infer<typeof VerbsIndexSchema>;
export type ConjugationTable = z.infer<typeof ConjugationTableSchema>;
export type Example = z.infer<typeof ExampleSchema>;
export type TenseFile = z.infer<typeof TenseFileSchema>;
export type ExampleFile = z.infer<typeof ExampleFileSchema>;
export type WortfamilieFile = z.infer<typeof WortfamilieFileSchema>;
export type Theme = z.infer<typeof ThemeSchema>;
